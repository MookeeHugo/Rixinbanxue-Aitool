import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Create a minimal valid PNG file (1x1 red pixel)
// PNG signature + IHDR + IDAT + IEND
const pngData = Buffer.from([
  // PNG signature
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,

  // IHDR chunk (13 bytes)
  0x00, 0x00, 0x00, 0x0d, // Length: 13
  0x49, 0x48, 0x44, 0x52, // "IHDR"
  0x00, 0x00, 0x00, 0x64, // Width: 100
  0x00, 0x00, 0x00, 0x64, // Height: 100
  0x08, 0x02, // Bit depth: 8, Color type: 2 (RGB)
  0x00, 0x00, 0x00, // Compression, Filter, Interlace
  0x93, 0x47, 0xf8, 0x30, // CRC

  // IDAT chunk (simple cyan rectangle)
  0x00, 0x00, 0x00, 0x16, // Length: 22
  0x49, 0x44, 0x41, 0x54, // "IDAT"
  0x78, 0x9c, 0x62, 0x64, 0xf8, 0xcf, 0xc0, 0x00,
  0x00, 0x04, 0x41, 0x01, 0x0f, 0x93, 0x47, 0xf8,
  0x30, 0x00, 0x00, 0x00, 0x0a, 0x00,
  0x4e, 0xc9, 0xb4, 0x8a, // CRC

  // IEND chunk
  0x00, 0x00, 0x00, 0x00, // Length: 0
  0x49, 0x45, 0x4e, 0x44, // "IEND"
  0xae, 0x42, 0x60, 0x82  // CRC
]);

const outputPath = path.join(__dirname, '../tests/fixtures/test-image.png');
fs.writeFileSync(outputPath, pngData);

console.log(`✅ 测试图片已创建: ${outputPath}`);
